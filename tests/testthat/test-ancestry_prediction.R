test_that("ancestry prediction", {
  tmpdir = tempdir()
  file.copy(test_path("testdata", "Sample01a_Sample_Report_2021_11_01_16_56_38.xlsx"), tmpdir)
  outpath = paste0(tempdir(), "/snp_sets/output/ancestry_prediction/Single/Sample01a/unconditioned")
  exp_centroids = read.csv(test_path("testdata", "Sample01a_major_unconditioned_AncestrySNPsOnly_Superpopulations_centroids_Calculations.txt"), header=T, sep="\t")
  obs_pcaplot = glue("{outpath}/PCA_plots/Sample01a_major_unconditioned_AncestrySNPsOnly_superpop_3D_PCAPlot.html")
  obs_centroids_pcaplot = glue("{outpath}/PCA_plots/Centroids_Plots/Sample01a_major_unconditioned_AncestrySNPsOnly_Superpopulations_centroids.html")
  run_mixder_ancestry(sample_manifest=test_path("testdata", "samplemanifest_01a.txt"), sample_reports=tmpdir, output="output", snps="ancestry", pcagroups="Superpopulations")
  obs_centroids = read.csv(glue("{outpath}/PCA_plots/Centroids_Plots/Sample01a_major_unconditioned_AncestrySNPsOnly_Superpopulations_centroids_Calculations.txt"), header=T, sep="\t")
  expect_true(file.exists(obs_pcaplot))
  expect_true(file.exists(obs_centroids_pcaplot))
  expect_equal(exp_centroids, obs_centroids)
  obs_pcaplot_all = glue("{outpath}/PCA_plots/Sample01a_major_unconditioned_AllSNPs_superpop_3D_PCAPlot.html")
  run_mixder_ancestry(sample = "Sample01a", sample_reports=tmpdir, output="output", snps="all", pcagroups="Superpopulations")
  obs_centroids_pcaplot_all = glue("{outpath}/PCA_plots/Centroids_Plots/Sample01a_major_unconditioned_AllSNPs_Superpopulations_centroids.html")
  expect_true(file.exists(obs_pcaplot_all))
  expect_true(file.exists(obs_centroids_pcaplot_all))
})
