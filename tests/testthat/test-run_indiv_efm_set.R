test_that("Running EFM", {
  outpath = tempdir()
  input = test_path("testdata", "Sample01a_set1.tsv")
  alla = test_path("testdata", "Sample01a_snpsetscombined_evidence.tsv")
  kin_a = test_path("testdata", "Sample01a_Sample_Report_2021_11_01_16_56_38.xlsx")
  file.copy(c(kin_a, input, alla), outpath)
  popFreq = mixder::popFreq_1000G
  refData = euroformix::sample_tableToList(euroformix::tableReader(test_path("testdata", "EFM_references.csv")))
  attable_efmmps = c(5, 0.1)
  attable_a = process_kinreport("Sample01a", "", outpath, 0.015, 10)
  expect_message(run_indiv_efm_set(1, "", outpath, popFreq, refData, "Sample01a", "", glue("{outpath}/output"), attable_a, TRUE, cond = NULL, uncond=TRUE), "Running unconditioned analysis for set 1, attempt #1")
  expect_message(run_indiv_efm_set(1, "", outpath, popFreq, refData, "Sample01a", "", glue("{outpath}/output"), attable_a, TRUE, cond = c("Ref1"), uncond=TRUE), "Running mixture deconvolution conditioned on Ref1")
  expect_message(run_indiv_efm_set(1, "", outpath, popFreq, refData, "Sample01a", "", glue("{outpath}/output"), attable_a, TRUE, cond = c("Ref1", "Ref2"), uncond=TRUE), "Running mixture deconvolution conditioned on Ref2")
  expect_message(run_indiv_efm_set(1, "", outpath, popFreq, NULL, "Sample01a", "", glue("{outpath}/output"), attable_efmmps, TRUE, software="EFMmps", uncond=TRUE), "Running unconditioned analysis for set 1, attempt #1")
})
